package tipos;

public class divisionIntegers1 {

	public static void main(String[] args) {

		int num1 = 7;
		int num2 = 3;

		System.out.println(num1 / num2); // 2
		System.out.println(num1 / (float)num2); // 2.3333333
		System.out.println((float)num1 / num2); // cast cualquier operador
		System.out.println(num1 / (double)num2); // 2.3333333333333335
	}

}
